import { Annotations, CfnResource, Stack, type IAspect } from 'aws-cdk-lib';
import { CfnManagedPolicy, CfnPolicy } from 'aws-cdk-lib/aws-iam';
import type { IConstruct } from 'constructs';

/**
 * IAM hard limit: a customer managed policy document cannot exceed 6,144
 * characters, whereas an inline role policy may use up to 10,240.
 * https://docs.aws.amazon.com/IAM/latest/UserGuide/reference_iam-quotas.html
 */
const MANAGED_POLICY_MAX_CHARS = 6144;

/**
 * Rewrites every `AWS::IAM::Policy` (inline policy) in the scope into an
 * equivalent customer managed policy (`AWS::IAM::ManagedPolicy`) attached to
 * the same principals.
 *
 * Why this exists
 * ---------------
 * The `@aws/agentcore-cdk` L3 construct attaches the AgentCore runtime
 * execution permissions as an inline role policy and does not expose an option
 * to use a managed policy. Inline policies are not independently versioned,
 * cannot be audited or reused as a standalone resource, and are reported by
 * AWS Config rule `iam-no-inline-policy-check` (cdk-nag
 * `HIPAA.Security-IAMNoInlinePolicy`, NIST 800-53 AC-6, HIPAA 164.308(a)(4)).
 *
 * Rather than suppressing the finding, this aspect converts the generated
 * policies at synthesis time so the deployed template contains only managed
 * policies. The permission set is unchanged — only the resource type and
 * attachment mechanism differ.
 *
 * Behaviour notes
 * ---------------
 * - The managed policy name is left unset so CloudFormation generates it. This
 *   avoids `CAPABILITY_NAMED_IAM` and cross-stack name collisions.
 * - Dependencies pointing at the inline policy are re-pointed at the managed
 *   policy so ordering guarantees (for example "runtime waits for its
 *   permissions") are preserved.
 * - If a document would exceed the 6,144 character managed policy quota the
 *   original inline policy is left in place and an error annotation is raised,
 *   so the situation surfaces at synth time instead of failing at deploy time.
 *
 * Apply it with `AspectPriority.MUTATING` so it runs before read-only aspects
 * such as the cdk-nag rule packs.
 */
export class InlinePolicyToManagedPolicy implements IAspect {
  /** Logical construct paths that were converted, for reporting. */
  public readonly converted: string[] = [];

  public visit(node: IConstruct): void {
    if (node instanceof CfnPolicy) {
      this.convert(node);
      return;
    }

    // Escaped / generic L1s cannot be converted safely because their
    // properties are not typed. Surface them instead of silently passing.
    if (CfnResource.isCfnResource(node) && node.cfnResourceType === 'AWS::IAM::Policy') {
      Annotations.of(node).addError(
        'Untyped AWS::IAM::Policy resource cannot be converted to a customer managed policy. ' +
          'Define it as an iam.CfnPolicy or replace it with iam.CfnManagedPolicy.',
      );
    }
  }

  private convert(policy: CfnPolicy): void {
    const scope = policy.node.scope;
    if (!scope) {
      return;
    }

    const id = policy.node.id;
    const path = policy.node.path;
    const document = policy.policyDocument;

    const documentSize = JSON.stringify(Stack.of(policy).resolve(document) ?? {}).length;
    if (documentSize > MANAGED_POLICY_MAX_CHARS) {
      Annotations.of(policy).addError(
        `Inline policy document is ${documentSize} characters and exceeds the ${MANAGED_POLICY_MAX_CHARS} ` +
          'character customer managed policy quota. Split the statements across multiple policies before ' +
          'converting, or grant an exception for this resource.',
      );
      return;
    }

    if (!policy.roles?.length && !policy.users?.length && !policy.groups?.length) {
      Annotations.of(policy).addWarning(
        `Inline policy ${path} has no attached principals; the generated managed policy will be unattached.`,
      );
    }

    const managed = new CfnManagedPolicy(scope, `${id}ManagedPolicy`, {
      policyDocument: document,
      description: `Customer managed replacement for inline policy ${policy.policyName} (${path}). ` +
        'Generated by the InlinePolicyToManagedPolicy aspect.',
      roles: policy.roles,
      users: policy.users,
      groups: policy.groups,
    });

    // Carry over dependencies the inline policy declared itself.
    for (const dependency of policy.obtainDependencies()) {
      if (CfnResource.isCfnResource(dependency)) {
        managed.addDependency(dependency);
      }
    }

    // Re-point anything that depended on the inline policy.
    for (const other of Stack.of(policy).node.findAll()) {
      if (other === policy || !CfnResource.isCfnResource(other)) {
        continue;
      }
      if (other.obtainDependencies().includes(policy)) {
        other.removeDependency(policy);
        other.addDependency(managed);
      }
    }

    scope.node.tryRemoveChild(id);
    this.converted.push(path);
  }
}
